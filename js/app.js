  setupEventListeners() {
    // Search input
    const searchInput = document.getElementById("search-input");
    if (searchInput) {
      searchInput.addEventListener("input", (e) => {
        this.searchQuery = e.target.value.toLowerCase().trim();
        this.renderQuestionBank();
      });
    }

    // Main Exam Switcher Tabs (SAT 2026 vs IELTS 2026)
    document.querySelectorAll(".exam-tab-btn").forEach(btn => {
      btn.addEventListener("click", (e) => {
        document.querySelectorAll(".exam-tab-btn").forEach(b => b.classList.remove("active"));
        e.currentTarget.classList.add("active");
        this.activeExamTab = e.currentTarget.getAttribute("data-exam");
        this.activeSectionFilter = "all";
        this.renderSectionFilters();
        this.renderQuestionBank();
      });
    });

    // Navigation items (Sidebar & Mobile bar)
    document.querySelectorAll("[data-nav-target]").forEach(nav => {
      nav.addEventListener("click", (e) => {
        const target = e.currentTarget.getAttribute("data-nav-target");
        this.handleNavSwitch(target);
      });
    });

    // Desmos Calculator buttons
    document.querySelectorAll(".btn-open-desmos").forEach(btn => {
      btn.addEventListener("click", () => {
        window.desmosManager?.toggle(true);
      });
    });

    // Shadowing Trainer buttons
    document.querySelectorAll(".btn-open-shadowing").forEach(btn => {
      btn.addEventListener("click", () => {
        window.shadowingTrainer?.openTrainer();
      });
    });

    // AI Assistant Toggle
    document.querySelectorAll(".btn-open-ai").forEach(btn => {
      btn.addEventListener("click", () => this.openAIChat());
    });

    // AI Quick Suggestion Pills
    document.querySelectorAll(".ai-quick-pill").forEach(pill => {
      pill.addEventListener("click", () => {
        const query = pill.getAttribute("data-query");
        if (query && window.aiAssistant) {
          window.aiAssistant.processUserQuery(query);
        }
      });
    });

    // AI Send button
    const aiSendBtn = document.getElementById("ai-send-btn");
    const aiInput = document.getElementById("ai-user-input");
    const aiMicBtn = document.getElementById("ai-mic-btn");

    if (aiSendBtn && aiInput) {
      const sendAI = () => {
        const txt = aiInput.value.trim();
        if (txt) {
          window.aiAssistant.processUserQuery(txt);
          aiInput.value = "";
        }
      };
      aiSendBtn.addEventListener("click", sendAI);
      aiInput.addEventListener("keydown", (e) => {
        if (e.key === "Enter") sendAI();
      });

      // AI Mic Speech Recognition
      if (aiMicBtn) {
        const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
        if (SpeechRecognition) {
          let recognition = null;
          let isListening = false;

          try {
            recognition = new SpeechRecognition();
            recognition.continuous = false;
            recognition.interimResults = true;

            recognition.onstart = () => {
              isListening = true;
              aiMicBtn.classList.add("listening");
              aiInput.placeholder = this.currentLang === "ru" ? "Слушаю... Говорите" : (this.currentLang === "en" ? "Listening... Speak now" : "Tinglayapman... Gapiring");
            };

            recognition.onresult = (event) => {
              let transcript = "";
              for (let i = event.resultIndex; i < event.results.length; i++) {
                transcript += event.results[i][0].transcript;
              }
              aiInput.value = transcript;
            };

            recognition.onend = () => {
              isListening = false;
              aiMicBtn.classList.remove("listening");
              aiInput.placeholder = this.currentLang === "ru" ? "Задайте вопрос по SAT или IELTS 2026..." : (this.currentLang === "en" ? "Ask anything about SAT or IELTS 2026..." : "SAT yoki IELTS 2026 savollari bo'yicha so'rang...");
              const text = aiInput.value.trim();
              if (text) {
                sendAI();
              }
            };

            recognition.onerror = () => {
              isListening = false;
              aiMicBtn.classList.remove("listening");
            };

            aiMicBtn.addEventListener("click", () => {
              if (isListening) {
                recognition.stop();
              } else {
                recognition.lang = this.currentLang === "ru" ? "ru-RU" : (this.currentLang === "en" ? "en-US" : "uz-UZ");
                try {
                  recognition.start();
                } catch (err) {
                  console.warn("Speech recognition start:", err);
                }
              }
            });
          } catch (e) {
            console.warn("Speech recognition init:", e);
          }
        } else {
          aiMicBtn.addEventListener("click", () => {
            this.notify(this.currentLang === "ru" ? "Голосовой ввод не поддерживается браузером." : (this.currentLang === "en" ? "Speech recognition not supported." : "Brauzeringiz ovozli qidiruvni qo'llab-quvvatlamaydi."));
          });
        }
      }
    }

    // Tools Floating Dropdown
    const toolsBtn = document.getElementById("btn-toggle-tools-menu");
    const toolsMenu = document.getElementById("tools-floating-menu");
    const toolsWrapper = document.querySelector(".tools-dropdown-wrapper");
    if (toolsBtn && toolsMenu) {
      toolsBtn.addEventListener("click", (e) => {
        e.stopPropagation();
        const isOpen = toolsMenu.classList.contains("show");
        toolsMenu.classList.toggle("show", !isOpen);
        toolsWrapper?.classList.toggle("open", !isOpen);
      });

      document.addEventListener("click", (e) => {
        if (!toolsWrapper?.contains(e.target)) {
          toolsMenu.classList.remove("show");
          toolsWrapper?.classList.remove("open");
        }
      });

      toolsMenu.querySelectorAll(".dropdown-item").forEach(item => {
        item.addEventListener("click", () => {
          toolsMenu.classList.remove("show");
          toolsWrapper?.classList.remove("open");
        });
      });
    }
  }

