  // ================= PREMIUM INTERACTIVE ANIMATIONS & SCROLL REVEAL =================
  initAnimations() {
    // 1. Scroll Reveal Animations (Intersection Observer)
    if ("IntersectionObserver" in window) {
      const revealTargets = document.querySelectorAll(
        ".exam-category-block, .bento-stats-grid, .topqir-games-container, .ommaviy-section, .faq-container, .stats-summary-grid, .hero-stat-col"
      );

      revealTargets.forEach(el => el.classList.add("scroll-reveal"));

      const revealObserver = new IntersectionObserver((entries, obs) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            entry.target.classList.add("revealed");
            obs.unobserve(entry.target);
          }
        });
      }, {
        threshold: 0.1,
        rootMargin: "0px 0px -30px 0px"
      });

      revealTargets.forEach(el => revealObserver.observe(el));
    }

    // 2. Dynamic Animated Counter for Hero Stats
    this.initAnimatedCounters();
  }

  initAnimatedCounters() {
    const statsRow = document.querySelector(".topqir-hero-stats-row");
    if (!statsRow || !("IntersectionObserver" in window)) return;

    let hasCounted = false;
    const countUp = (el, target, duration = 1600) => {
      const startTime = performance.now();
      const isDecimal = target.includes(".");
      const numTarget = parseFloat(target.replace(/[^0-9.]/g, ""));
      const suffix = target.replace(/[0-9.,]/g, "");

      const frame = (now) => {
        const progress = Math.min((now - startTime) / duration, 1);
        const ease = progress === 1 ? 1 : 1 - Math.pow(2, -10 * progress);
        const current = isDecimal ? (numTarget * ease).toFixed(1) : Math.floor(numTarget * ease);
        el.textContent = (isDecimal ? current : current.toLocaleString("en-US")) + suffix;

        if (progress < 1) {
          requestAnimationFrame(frame);
        } else {
          el.textContent = target;
        }
      };
      requestAnimationFrame(frame);
    };

    const statsObserver = new IntersectionObserver((entries) => {
      if (entries[0] && entries[0].isIntersecting && !hasCounted) {
        hasCounted = true;
        const statTests = document.getElementById("hero-stat-tests");
        const statUsers = document.getElementById("hero-stat-users");
        const statPass = document.getElementById("hero-stat-pass");

        if (statTests) countUp(statTests, "48,930+");
        if (statUsers) countUp(statUsers, "1,850+");
        if (statPass) countUp(statPass, "99.2%");
        statsObserver.disconnect();
      }
    }, { threshold: 0.15 });

    statsObserver.observe(statsRow);
  }

  // ================= 1. THEME MANAGEMENT (LIGHT SAAS STANDARD) =================
  initTheme() {
    try {
      localStorage.removeItem("yu_theme");
    } catch (e) {}
    document.body.classList.remove("dark-theme");
    document.documentElement.setAttribute("data-theme", "light");
  }

  applyTheme(theme, notify = false) {
    // Platform operates exclusively in modern Light SaaS theme
    document.body.classList.remove("dark-theme");
    document.documentElement.setAttribute("data-theme", "light");
  }

  toggleTheme() {
    // Dark mode permanently disabled per platform guidelines
  }

  // ================= 2. LANGUAGE MANAGEMENT (UZ / RU / EN) =================
  initLanguage() {
    this.applyLanguage(this.currentLang, false);
  }

  applyLanguage(lang, notify = true) {
    this.currentLang = lang;
    const dict = YU_I18N[lang] || YU_I18N.uz;

    // 1. Update Flag Button Icons & Tooltips
    const flagElements = document.querySelectorAll("#lang-toggle-btn, .capsule-flag-pill");
    flagElements.forEach(el => {
      if (lang === "uz") {
        el.innerHTML = "<span>🇺🇿</span>";
        el.title = "Til: O'zbekcha (Bosilsa Rus tiliga o'tadi) 🇺🇿";
      } else if (lang === "ru") {
        el.innerHTML = "<span>🇷🇺</span>";
        el.title = "Язык: Русский (Нажмите для переключения на English) 🇷🇺";
      } else {
        el.innerHTML = "<span>🇬🇧</span>";
        el.title = "Language: English (Click to switch to O'zbekcha) 🇬🇧";
      }
    });

    // 2. Translate all [data-i18n] elements
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // 3. Translate Section Headings, Descriptions & Cards across the page
    this.translateFullDOM(lang, dict);

    // 4. Translate Search Placeholders
    const searchInput = document.getElementById("search-input");
    if (searchInput && dict.search_placeholder) {
      searchInput.placeholder = dict.search_placeholder;
    }

    // 5. Update Auth Headers & Modals
    window.authManager?.renderHeaderAuth();

    // 6. Update Teacher Studio Texts
    window.teacherStudio?.updateLanguage(lang);

    // 7. Re-render Dynamic Filter Chips & Question Cards
    this.renderSectionFilters();
    this.renderQuestionBank();

    // 8. Notification
    if (notify) {
      this.notify(dict.toast_lang_switch || "Til o'zgartirildi!");
    }
  }

